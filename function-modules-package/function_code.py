# addition
def addition(num1, num2):
    result = num1 + num2
    return result


# subtraction
def subtraction(num1, num2):
    result = num1 - num2
    return result


# multiplication
def multiplication(num1, num2):
    result = num1 * num2
    return result


# division
def division(num1, num2):
    result = num1 / num2
    return result


# floor division
def floor_division(num1, num2):
    result = num1 // num2
    return result


# modulus
def modulus(num1, num2):
    result = num1 % num2
    return result


# exponentiation
def exponentiation(num1, num2):
    result = num1 ** num2
    return result

