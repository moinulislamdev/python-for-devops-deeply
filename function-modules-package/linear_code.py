a = 30
b = 22

# addition
addition = a + b
print(addition)

# subtraction
subtraction = a - b
print(subtraction)

# multiplication
multiplication = a * b
print(multiplication)

# division
division = a / b
print(division)

# floor division
floor_division = a // b
print(floor_division)

# modulus (remainder)
modulus = a % b
print(modulus)

# exponentiation (power)
exponentiation = a ** b
print(exponentiation)